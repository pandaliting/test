# 为什么需要RAG
#1、大模型具有滞后性 2、大模型有幻觉 3、大模型缺乏专业的领域知识
# 每次提问时，基于我们的知识库和问题一起提供给LLM
###
# RAG详细的工作流程：
#1、索引构建阶段（知识库生成）准备数据->数据加载->文本拆分->向量化->向量存储
#2、检索增强生成 提出问题->问题向量化->向量检索（召回阶段）->构建提示词->大模型生成答案
###

# 文本拆分 token浪费、降低响应速度、干扰文本生成
# 向量化就是将文本拆分的后的每一个语义片段转化为的高维向量
# 为什么向量化：捕捉文本之间的语义相似度      相似度=函数（候选文本，用户问题）
# 如何向量化：使用嵌入模型实现
# 向量存储：将向量化后的数值向量和原始的文本片段，以键值的形式存储在向量数据库中

